from __future__ import annotations
import os
import re
import uuid
import logging
from pathlib import Path
from orchestra.models import Playbook, PlaybookTask, PlaybookTaskStatus
from orchestra.engine.runners.ask_runner import run_ask

logger = logging.getLogger(__name__)

class PlaybookParser:
    TASK_REGEX = re.compile(r'^(\s*)- \[([ xX])\] (.*)')
    HALT_REGEX = re.compile(r'<!-- orchestra:halt: (.*?) -->')

    @classmethod
    def parse(cls, path: str | Path) -> Playbook:
        path_obj = Path(path)
        if not path_obj.exists():
            raise FileNotFoundError(f"Playbook not found: {path}")

        content = path_obj.read_text()
        tasks = []
        halt_reason = None
        
        for i, line in enumerate(content.splitlines()):
            halt_match = cls.HALT_REGEX.search(line)
            if halt_match:
                halt_reason = halt_match.group(1).strip()
            
            task_match = cls.TASK_REGEX.match(line)
            if task_match:
                indent, check, desc = task_match.groups()
                status = PlaybookTaskStatus.COMPLETED if check.strip().lower() == 'x' else PlaybookTaskStatus.PENDING
                tasks.append(PlaybookTask(
                    id=uuid.uuid4().hex[:8],
                    description=desc,
                    status=status,
                    line_number=i,
                    original_line=line
                ))
                
        return Playbook(path=str(path), tasks=tasks, halt_reason=halt_reason)

    @classmethod
    def write_status(cls, playbook: Playbook, task_idx: int, new_status: PlaybookTaskStatus, error: str = None) -> None:
        path_obj = Path(playbook.path)
        lines = path_obj.read_text().splitlines()
        
        task = playbook.tasks[task_idx]
        task.status = new_status
        if error:
            task.error = error

        check = 'x' if new_status == PlaybookTaskStatus.COMPLETED else ' '
        # Replace the checkmark in the original line
        original = lines[task.line_number]
        match = cls.TASK_REGEX.match(original)
        if match:
            indent, _, desc = match.groups()
            new_line = f"{indent}- [{check}] {desc}"
            if error:
                new_line += f" <!-- error: {error} -->"
            lines[task.line_number] = new_line
            path_obj.write_text("\n".join(lines) + "\n")

class PlaybookRunner:
    def __init__(self, alias: str = "cld-fast"):
        self.alias = alias

    def run(self, playbook_path: str) -> None:
        playbook = PlaybookParser.parse(playbook_path)
        logger.info(f"Starting playbook: {playbook_path} with {len(playbook.tasks)} tasks.")

        if playbook.halt_reason:
            logger.warning(f"Playbook halted: {playbook.halt_reason}")
            return

        for idx, task in enumerate(playbook.tasks):
            if task.status != PlaybookTaskStatus.PENDING:
                continue

            # Fresh context per task
            logger.info(f"Running task {idx+1}/{len(playbook.tasks)}: {task.description}")
            PlaybookParser.write_status(playbook, idx, PlaybookTaskStatus.RUNNING)
            
            try:
                run_obj = run_ask(self.alias, task.description, show_live=False)
                
                # Check for halt markers generated by the agent
                if run_obj.agents and run_obj.agents[0].stdout_log:
                    halt_match = PlaybookParser.HALT_REGEX.search(run_obj.agents[0].stdout_log)
                    if halt_match:
                        reason = halt_match.group(1).strip()
                        PlaybookParser.write_status(playbook, idx, PlaybookTaskStatus.FAILED, error=reason)
                        self._inject_halt(playbook, reason)
                        break

                if run_obj.status.value == "completed":
                    PlaybookParser.write_status(playbook, idx, PlaybookTaskStatus.COMPLETED)
                else:
                    PlaybookParser.write_status(playbook, idx, PlaybookTaskStatus.FAILED, error="Task failed")
                    break # Stop on first failure
            except Exception as e:
                logger.exception(f"Error running playbook task {task.id}")
                PlaybookParser.write_status(playbook, idx, PlaybookTaskStatus.FAILED, error=str(e))
                break

    def _inject_halt(self, playbook: Playbook, reason: str) -> None:
        path_obj = Path(playbook.path)
        content = path_obj.read_text()
        content += f"\n<!-- orchestra:halt: {reason} -->\n"
        path_obj.write_text(content)
